export interface VerbEntry {
  id: string;
  infinitive: string;
  english: string;
  category: string;
  frequency: number;
}

export const VERBS: VerbEntry[] = VERB_SOURCE.map((raw, i) => {
  const [infinitive, english, category, freq] = raw.split('=');
  return {
    id: `v-${i}`,
    infinitive: infinitive.trim(),
    english: english.trim(),
    category: (category || 'core').trim(),
    frequency: Number(freq) || 3,
  };
});

export const VERB_CATEGORIES = Array.from(new Set(VERBS.map(v => v.category))).sort();
